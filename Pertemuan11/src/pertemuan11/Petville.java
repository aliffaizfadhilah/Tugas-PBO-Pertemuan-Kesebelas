    private void UploadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UploadActionPerformed

        JFileChooser jfc = new JFileChooser(FileSystemView.getFileSystemView().getHomeDirectory());
        int returnValue = jfc.showOpenDialog(null);
        if (returnValue == JFileChooser.APPROVE_OPTION) {
            File filePilihan = jfc.getSelectedFile();
            try (BufferedReader br = new BufferedReader(new FileReader(filePilihan))) {
                String baris;
                String pemisah = ";";
                em.getTransaction().begin();
                while ((baris = br.readLine()) != null) {
                    // Hilangkan karakter BOM atau karakter tidak terlihat
                    baris = baris.replace("\uFEFF", "").trim();

                    String[] data = baris.split(pemisah);
                    if (data.length < 4 || data[0].equalsIgnoreCase("id_hewan")) {
                        continue;
                    }

                    // Bersihkan spasi dan karakter aneh pada setiap kolom
                    String idHewan = data[0].replaceAll("[^\\p{Print}]", "").trim();
                    String namaHewan = data[1].trim();
                    String jenisHewan = data[2].trim();
                    int harga = Integer.parseInt(data[3].trim());

                    Petville_1 p = new Petville_1(data[0].trim());
                    p.setNamaHewan(data[1].trim());
                    p.setJenisHewan(data[2].trim());
                    p.setHarga(Integer.parseInt(data[3].trim()));
                    em.persist(p);
                }
                em.getTransaction().commit();
                JOptionPane.showMessageDialog(this, "Upload selesai!");
                tampilData();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Gagal upload: " + ex.getMessage());
            }
        }

    }//GEN-LAST:event_UploadActionPerformed

