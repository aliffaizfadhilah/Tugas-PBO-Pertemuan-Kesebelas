    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("id_hewan");
        model.addColumn("nama_hewan");
        model.addColumn("jenis_hewan");
        model.addColumn("harga");

        EntityManager emLocal = emf.createEntityManager(); // Buat EM baru setiap kali

        try {
            List<Petville_1> list = emLocal.createNamedQuery("Petville_1.findAll", Petville_1.class).getResultList();

            // Kosongkan tabel dan isi ulang
            model.setRowCount(0);
            for (Petville_1 p : list) {
                model.addRow(new Object[]{
                    p.getIdHewan(),
                    p.getNamaHewan(),
                    p.getJenisHewan(),
                    p.getHarga()
                });
            }

            tabelPetville.setModel(model);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan data: " + e.getMessage());
        } finally {
            emLocal.close(); // Tutup EM agar tidak menumpuk
        }
    }

